/* Coin customisation: material, face symbols, custom text, and image coins from /coins.
   Arcade.coins.attach(stage, customize) adds two sections to the Customize panel and
   returns { sparks } so the spark effects can match the coin's metal. */
Arcade.coins = (() => {
  const KEY = { material: 'arcade.coin.material', faces: 'arcade.coin.faces', custom: 'arcade.coin.custom',
    size: 'arcade.coin.size', thick: 'arcade.coin.thickness', edge: 'arcade.coin.edge' };
  const read = (k) => { try { return localStorage.getItem(k); } catch (e) { return null; } };
  const write = (k, v) => { try { localStorage.setItem(k, v); } catch (e) { /* storage blocked: choice won't persist */ } };
  const pretty = (f) => f.replace(/\.[^.]+$/, '').replace(/[-_]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

  // ---- materials: colours for the face, rim, edge and engraved symbol, plus matching spark colours ----
  const M = (id, label, face, rim, edge, eb, glyph, shadow, ring, inner, glow, sparks) => ({
    id, label, sparks,
    swatch: `radial-gradient(circle at 32% 28%, ${face[0]}, ${face[1]} 45%, ${face[2]} 85%)`,
    vars: { '--cn-1': face[0], '--cn-2': face[1], '--cn-3': face[2], '--cn-rim': rim, '--cn-e1': edge[0], '--cn-e2': edge[1],
      '--cn-eb': eb, '--cn-glyph': glyph, '--cn-glyph-shadow': shadow, '--cn-ring': ring, '--cn-inner': inner, '--cn-glow': glow },
  });
  const NO_GLOW = '0 0 0 transparent';
  const MATERIALS = [
    M('gold', 'Gold', ['#fff0a8', '#ffcf3f', '#d9a400'], '#e3ac00', ['#e8b92a', '#a87800'], '#8f6500', '#a26f00',
      '0 2px 0 #ffeaa0,0 -1px 0 rgba(90,60,0,.5)', 'rgba(130,90,0,.45)', 'rgba(120,80,0,.45)', NO_GLOW, ['#ffcf3f', '#ffe58a']),
    M('silver', 'Silver', ['#ffffff', '#d5dae3', '#8d96a8'], '#aeb6c6', ['#dfe4ee', '#7f889b'], '#6b7488', '#5b6478',
      '0 2px 0 #ffffff,0 -1px 0 rgba(40,50,70,.5)', 'rgba(70,80,100,.5)', 'rgba(40,50,70,.45)', NO_GLOW, ['#e6ebf5', '#ffffff']),
    M('bronze', 'Bronze', ['#f3c59a', '#cd7f32', '#8a4f17'], '#a8611d', ['#c98a4b', '#7a4510'], '#5e3409', '#6a3c0e',
      '0 2px 0 #f6d3ad,0 -1px 0 rgba(60,30,5,.5)', 'rgba(90,50,10,.5)', 'rgba(70,35,5,.5)', NO_GLOW, ['#cd7f32', '#f0a860']),
    M('rose-gold', 'Rose Gold', ['#ffe0dc', '#f0a8a0', '#c46f6a'], '#d98b85', ['#efb2aa', '#a85a55'], '#8a4743', '#8f4a46',
      '0 2px 0 #fff0ee,0 -1px 0 rgba(100,40,36,.5)', 'rgba(120,60,55,.5)', 'rgba(110,45,40,.45)', NO_GLOW, ['#f0a8a0', '#ffd5d0']),
    M('obsidian', 'Obsidian', ['#4a5170', '#1e2236', '#0a0c16'], '#2c3350', ['#2f3552', '#0c0f1d'], '#05060d', '#7fd8ff',
      '0 0 10px rgba(90,209,255,.8),0 0 2px #7fd8ff', 'rgba(127,216,255,.45)', 'rgba(0,0,0,.7)', '0 0 14px rgba(90,209,255,.25)', ['#5ad1ff', '#b388ff']),
    M('neon', 'Neon', ['#ffd0f5', '#ff4fd8', '#a1089b'], '#ff7be8', ['#ff6fe0', '#8a0885'], '#6b0667', '#ffffff',
      '0 0 10px #fff,0 0 4px #ffd0f5', 'rgba(255,255,255,.5)', 'rgba(80,0,70,.5)', '0 0 18px 2px rgba(255,79,216,.55)', ['#ff4fd8', '#ffd0f5']),
  ];

  // ---- face symbols ----
  const SYMBOLS = [['H', 'T'], ['★', '☾'], ['♛', '⚓'], ['🙂', '🙃'], ['☀️', '🌙']];
  const seg = window.Intl && Intl.Segmenter ? new Intl.Segmenter() : null;
  const chars = (s) => (seg ? [...seg.segment(s)].map((x) => x.segment) : [...s]);
  const clip = (s) => chars(s.trim()).slice(0, 3).join('');            // up to 3 characters per face
  const scale = (n) => (n <= 1 ? 1 : n === 2 ? 0.75 : 0.55);            // longer text gets a smaller font

  // coins/manifest.js (generated by scripts/build-backgrounds.mjs) lists the image coins
  let loading = null;
  const manifest = () => loading || (loading = new Promise((done) => {
    if (window.ARCADE_COINS) return done(window.ARCADE_COINS);
    const s = document.createElement('script');
    s.src = 'coins/manifest.js';
    s.onload = () => done(window.ARCADE_COINS || []);
    s.onerror = () => done([]);
    document.head.append(s);
  }));
  const loadImg = (src) => new Promise((ok, no) => { const i = new Image(); i.onload = ok; i.onerror = no; i.src = src; });

  // a radiogroup of buttons with arrow-key navigation
  function radios(label, items, render) {
    const el = document.createElement('div');
    el.className = 'bg-grid'; el.setAttribute('role', 'radiogroup'); el.setAttribute('aria-label', label);
    let handler = () => {};
    const btns = items.map((it, i) => {
      const b = document.createElement('button');
      b.type = 'button'; b.className = 'bg-opt'; b.title = it.label;
      b.setAttribute('role', 'radio'); b.setAttribute('aria-checked', 'false');
      render(b, it);
      b.onclick = () => handler(it, true);
      b.onkeydown = (e) => {
        const d = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
        if (!d) return;
        e.preventDefault();
        const j = (i + d + items.length) % items.length;
        handler(items[j], true); btns[j].focus();
      };
      el.append(b);
      return b;
    });
    return {
      el,
      mark(item) { btns.forEach((b, i) => { const on = items[i] === item; b.setAttribute('aria-checked', String(on)); b.tabIndex = on ? 0 : -1; }); },
      onPick(fn) { handler = fn; },
    };
  }
  const span = (cls, text) => { const s = document.createElement('span'); s.className = cls; if (text != null) s.textContent = text; return s; };

  function attach(stage, cz) {
    const coinEl = stage.querySelector('.coin');
    const glyphH = stage.querySelector('.face.front .rim span'), glyphT = stage.querySelector('.face.back .rim span');
    const look = { sparks: MATERIALS[0].sparks };

    // material
    const mats = radios('Coin material', MATERIALS, (b, m) => {
      const sw = span('sw'); sw.style.background = m.swatch;
      b.append(sw, span('bg-name', m.label));
    });
    cz.add('Coin material', mats.el);
    function setMaterial(m, save) {
      Object.entries(m.vars).forEach(([k, v]) => stage.style.setProperty(k, v));
      look.sparks = m.sparks; mats.mark(m);
      if (save) write(KEY.material, m.id);
    }
    mats.onPick(setMaterial);
    setMaterial(MATERIALS.find((m) => m.id === read(KEY.material)) || MATERIALS[0], false);

    // faces
    let custom = ['', ''];
    try { const c = JSON.parse(read(KEY.custom)); if (Array.isArray(c) && c.length === 2) custom = [String(c[0]), String(c[1])]; } catch (e) { /* none saved */ }

    const holder = document.createElement('div');
    const row = document.createElement('div'); row.className = 'cn-custom'; row.hidden = true;
    const field = (label, i, ph) => {
      const l = document.createElement('label'), inp = document.createElement('input');
      l.append(label, inp); inp.type = 'text'; inp.placeholder = ph; inp.value = custom[i]; inp.autocomplete = 'off';
      inp.oninput = () => {
        custom[i] = clip(inp.value); write(KEY.custom, JSON.stringify(custom));
        if (current && current.kind === 'custom') showText(custom[0], custom[1]);
      };
      return l;
    };
    row.append(field('Heads', 0, 'H'), field('Tails', 1, 'T'));
    holder.append(row);
    cz.add('Coin faces', holder);

    let faces = null, items = [], current = null;
    function glyph(el, text) { el.textContent = text; el.style.setProperty('--cn-gk', scale(chars(text).length)); }
    function showText(h, t) { coinEl.classList.remove('img'); glyph(glyphH, h || 'H'); glyph(glyphT, t || 'T'); }

    function setFaces(item, save) {
      current = item; faces.mark(item); row.hidden = item.kind !== 'custom';
      if (save) write(KEY.faces, item.id);
      if (item.kind === 'sym') showText(item.h, item.t);
      else if (item.kind === 'custom') showText(custom[0], custom[1]);
      else {                                           // image coin: preload both faces, then swap
        Promise.all([loadImg(item.heads), loadImg(item.tails)]).then(() => {
          if (current !== item) return;
          stage.style.setProperty('--cn-img-h', `url("${item.heads}")`);
          stage.style.setProperty('--cn-img-t', `url("${item.tails}")`);
          coinEl.classList.add('img');
        }).catch(() => { if (current === item) setFaces(items[0], false); });
      }
    }

    manifest().then((coins) => {
      items = SYMBOLS.map(([h, t], i) => ({ id: 'sym:' + i, kind: 'sym', h, t, label: h + ' / ' + t }))
        .concat([{ id: 'custom', kind: 'custom', label: 'Custom' }])
        .concat(coins.map((c) => ({
          id: 'img:' + c.id, kind: 'img', label: pretty(c.id),
          heads: 'coins/' + encodeURIComponent(c.heads), tails: 'coins/' + encodeURIComponent(c.tails),
        })));
      faces = radios('Coin faces', items, (b, it) => {
        const thumb = span('face-thumb');
        if (it.kind === 'sym') thumb.textContent = it.h + ' ' + it.t;
        else if (it.kind === 'custom') thumb.textContent = '✎';
        else for (const src of [it.heads, it.tails]) { const im = new Image(); im.src = src; im.alt = ''; im.loading = 'lazy'; im.decoding = 'async'; thumb.append(im); }
        b.append(thumb, span('bg-name', it.label));
      });
      faces.onPick(setFaces);
      holder.prepend(faces.el);
      const saved = read(KEY.faces);
      setFaces(items.find((it) => it.id === saved) || items[0], false);
    });

    // ---- shape: size, thickness, edge style ----
    const DEFAULT = { size: 1, thick: 1, edge: 'smooth' };
    const EDGES = [{ id: 'smooth', label: 'Smooth' }, { id: 'reeded', label: 'Reeded' }, { id: 'coarse', label: 'Coarse' }, { id: 'banded', label: 'Banded' }];
    const num = (k, d, lo, hi) => { const v = parseFloat(read(k)); return Number.isFinite(v) ? Math.min(hi, Math.max(lo, v)) : d; };
    const shape = {
      size: num(KEY.size, DEFAULT.size, 0.4, 1.5),
      thick: num(KEY.thick, DEFAULT.thick, 0.4, 3),
      edge: (EDGES.find((e) => e.id === read(KEY.edge)) || EDGES[0]).id,
    };

    // The coin's side is a stack of discs; thicker coins get more discs so there are no visible gaps.
    const HALF = 0.047;
    function buildEdges() {
      const n = Math.max(8, Math.min(36, Math.round(14 * shape.thick)));
      coinEl.querySelectorAll('.edge').forEach((e) => e.remove());
      const frag = document.createDocumentFragment();
      for (let i = 0; i < n; i++) {
        const k = -HALF + (2 * HALF * i) / (n - 1), e = document.createElement('i');
        e.className = 'edge' + (Math.abs(k) < HALF / 3 ? ' mid' : '');   // middle discs: the "band" in Banded
        e.style.setProperty('--k', k.toFixed(4));
        frag.append(e);
      }
      coinEl.prepend(frag);
    }
    let edgeRaf = 0;
    const rebuildSoon = () => { cancelAnimationFrame(edgeRaf); edgeRaf = requestAnimationFrame(buildEdges); };
    const resized = () => stage.dispatchEvent(new Event('coinresize'));    // the game re-fits the coin

    const slider = (label, min, max, step, fmt, key, onInput) => {
      const l = document.createElement('label'), out = document.createElement('output'), inp = document.createElement('input');
      l.className = 'cn-slider'; inp.type = 'range'; inp.min = min; inp.max = max; inp.step = step;
      const show = () => { out.textContent = fmt(+inp.value); };
      inp.oninput = () => { show(); write(key, inp.value); onInput(+inp.value); };
      l.append(span('', label), out, inp);
      return { el: l, set(v) { inp.value = v; show(); } };
    };
    const sizeCtl = slider('Size', 0.4, 1.5, 0.05, (v) => Math.round(v * 100) + '%', KEY.size, (v) => { shape.size = v; resized(); });
    const thickCtl = slider('Thickness', 0.4, 3, 0.1, (v) => v.toFixed(1) + '×', KEY.thick, (v) => {
      shape.thick = v; stage.style.setProperty('--cn-th', v); rebuildSoon();
    });
    const edgeCtl = radios('Edge style', EDGES, (b, e) => { const t = span('edge-thumb'); t.dataset.edge = e.id; b.append(t, span('bg-name', e.label)); });
    function setEdge(e, save) {
      EDGES.forEach((x) => coinEl.classList.remove('edge-' + x.id));
      if (e.id !== 'smooth') coinEl.classList.add('edge-' + e.id);
      shape.edge = e.id; edgeCtl.mark(e);
      if (save) write(KEY.edge, e.id);
    }
    edgeCtl.onPick(setEdge);

    const reset = document.createElement('button');
    reset.type = 'button'; reset.className = 'cn-reset'; reset.textContent = 'Reset shape';
    reset.onclick = () => {
      Object.assign(shape, DEFAULT);
      sizeCtl.set(shape.size); thickCtl.set(shape.thick);
      [KEY.size, KEY.thick].forEach((k) => write(k, ''));
      stage.style.setProperty('--cn-th', shape.thick); buildEdges(); setEdge(EDGES[0], true); resized();
    };

    const box = document.createElement('div');
    box.append(sizeCtl.el, thickCtl.el, edgeCtl.el, reset);
    cz.add('Coin shape', box);
    sizeCtl.set(shape.size); thickCtl.set(shape.thick);
    stage.style.setProperty('--cn-th', shape.thick);
    buildEdges();
    setEdge(EDGES.find((e) => e.id === shape.edge), false);
    resized();

    return { get sparks() { return look.sparks; }, get sizeScale() { return shape.size; } };
  }

  return { attach };
})();
