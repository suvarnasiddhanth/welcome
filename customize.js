/* Customize panel + background picker.
   Arcade.customize(stage)        -> adds a "Customize" button to a game's stage; returns { add(title, node), destroy() }
   Arcade.backgrounds.attach(...) -> adds a Background section listing every image in /backgrounds */
Arcade.customize = function (stage) {
  const btn = document.createElement('button');
  btn.type = 'button'; btn.className = 'cz-btn'; btn.textContent = '🎨 Customize';
  btn.setAttribute('aria-haspopup', 'dialog'); btn.setAttribute('aria-expanded', 'false');
  const panel = document.createElement('div');
  panel.className = 'cz-panel'; panel.hidden = true;
  panel.setAttribute('role', 'dialog'); panel.setAttribute('aria-label', 'Customize');
  stage.append(btn, panel);

  const open = (on) => {
    panel.hidden = !on; btn.setAttribute('aria-expanded', String(on));
    if (on) { const t = panel.querySelector('[aria-checked="true"]') || panel.querySelector('button'); if (t) t.focus(); }
  };
  btn.onclick = () => open(panel.hidden);
  const away = (e) => { if (!panel.hidden && !panel.contains(e.target) && !btn.contains(e.target)) open(false); };
  const esc = (e) => { if (e.key === 'Escape' && !panel.hidden) { open(false); btn.focus(); } };
  document.addEventListener('pointerdown', away);
  document.addEventListener('keydown', esc);

  return {
    add(title, node) {
      const sec = document.createElement('section'), h = document.createElement('h3');
      h.textContent = title; sec.append(h, node); panel.append(sec);
    },
    destroy() { document.removeEventListener('pointerdown', away); document.removeEventListener('keydown', esc); },
  };
};

Arcade.backgrounds = (() => {
  const KEY = 'arcade.background';
  const read = () => { try { return localStorage.getItem(KEY); } catch (e) { return null; } };
  const write = (v) => { try { localStorage.setItem(KEY, v); } catch (e) { /* storage blocked: choice just won't persist */ } };
  // "reaching-hands.png" -> "Reaching Hands"
  const pretty = (f) => f.replace(/\.[^.]+$/, '').replace(/[-_]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

  // backgrounds/manifest.js (generated by scripts/build-backgrounds.mjs) lists the image files
  let loading = null;
  const manifest = () => loading || (loading = new Promise((done) => {
    if (window.ARCADE_BACKGROUNDS) return done(window.ARCADE_BACKGROUNDS);
    const s = document.createElement('script');
    s.src = 'backgrounds/manifest.js';
    s.onload = () => done(window.ARCADE_BACKGROUNDS || []);
    s.onerror = () => done([]);                      // no manifest: only the default is offered
    document.head.append(s);
  }));

  function attach(stage, customize) {
    const group = document.createElement('div');
    group.className = 'bg-grid'; group.setAttribute('role', 'radiogroup'); group.setAttribute('aria-label', 'Background');
    customize.add('Background', group);

    let items = [], buttons = [], current = null;

    function select(item, save) {
      current = item;
      buttons.forEach((b, i) => { const on = items[i] === item; b.setAttribute('aria-checked', String(on)); b.tabIndex = on ? 0 : -1; });
      if (save) write(item.id);
      if (!item.src) { stage.classList.remove('has-bg'); stage.style.removeProperty('--stage-bg'); return; }
      const img = new Image();                       // preload so the old background stays until the new one is ready
      img.onload = () => { if (current === item) { stage.style.setProperty('--stage-bg', `url("${item.src}")`); stage.classList.add('has-bg'); } };
      img.onerror = () => { if (current === item) select(items[0], false); };
      img.src = item.src;
    }

    manifest().then((files) => {
      items = [{ id: 'default', label: 'Default' }]
        .concat(files.map((f) => ({ id: f, label: pretty(f), src: 'backgrounds/' + encodeURIComponent(f) })));
      buttons = items.map((item, i) => {
        const b = document.createElement('button');
        b.type = 'button'; b.className = 'bg-opt'; b.title = item.label;
        b.setAttribute('role', 'radio'); b.setAttribute('aria-checked', 'false');
        const thumb = document.createElement('span'); thumb.className = 'bg-thumb';
        if (item.src) { const im = new Image(); im.src = item.src; im.alt = ''; im.loading = 'lazy'; im.decoding = 'async'; thumb.append(im); }
        const name = document.createElement('span'); name.className = 'bg-name'; name.textContent = item.label;
        b.append(thumb, name);
        b.onclick = () => select(item, true);
        b.onkeydown = (e) => {                       // arrow keys move through the options
          const d = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
          if (!d) return;
          e.preventDefault();
          const j = (i + d + items.length) % items.length;
          select(items[j], true); buttons[j].focus();
        };
        group.append(b);
        return b;
      });
      const saved = read();
      select(items.find((it) => it.id === saved) || items[0], false);
    });
  }

  return { attach };
})();
