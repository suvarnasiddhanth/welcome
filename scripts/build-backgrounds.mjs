// Lists every image in /backgrounds and writes backgrounds/manifest.js, which the site reads.
// Run locally with:  node scripts/build-backgrounds.mjs   (the deploy workflow also runs it for you)
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../backgrounds/', import.meta.url);
const IMAGE = /\.(png|jpe?g|webp|avif|gif|svg)$/i;

const files = readdirSync(dir).filter((f) => IMAGE.test(f)).sort((a, b) => a.localeCompare(b));

writeFileSync(
  new URL('manifest.js', dir),
  `/* AUTO-GENERATED by scripts/build-backgrounds.mjs. Do not edit by hand. */\nwindow.ARCADE_BACKGROUNDS = ${JSON.stringify(files, null, 2)};\n`
);
console.log(`backgrounds/manifest.js: ${files.length} image(s)\n  ` + files.join('\n  '));
