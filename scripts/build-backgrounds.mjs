// Lists the pictures that customise the site and writes the manifests the pages read:
//   backgrounds/manifest.js  <- every image in /backgrounds
//   coins/manifest.js        <- every complete coin in /coins: <name>-heads.<ext> + <name>-tails.<ext>
// Run locally with:  node scripts/build-backgrounds.mjs   (the deploy workflow also runs it for you)
import { readdirSync, writeFileSync } from 'node:fs';

const IMAGE = /\.(png|jpe?g|webp|avif|gif|svg)$/i;
const HEADER = '/* AUTO-GENERATED by scripts/build-backgrounds.mjs. Do not edit by hand. */\n';
const list = (dir) => readdirSync(dir).filter((f) => IMAGE.test(f)).sort((a, b) => a.localeCompare(b));

// backgrounds
const bgDir = new URL('../backgrounds/', import.meta.url);
const backgrounds = list(bgDir);
writeFileSync(new URL('manifest.js', bgDir), `${HEADER}window.ARCADE_BACKGROUNDS = ${JSON.stringify(backgrounds, null, 2)};\n`);
console.log(`backgrounds/manifest.js: ${backgrounds.length} image(s)`);
backgrounds.forEach((f) => console.log('  ' + f));

// coins: pair up <name>-heads.* with <name>-tails.*
const coinDir = new URL('../coins/', import.meta.url);
const groups = {};
for (const f of list(coinDir)) {
  const m = f.match(/^(.+)-(heads|tails)\.[a-z0-9]+$/i);
  if (!m) { console.warn(`  skipped coins/${f}: name it <name>-heads.<ext> or <name>-tails.<ext>`); continue; }
  (groups[m[1]] ||= {})[m[2].toLowerCase()] = f;
}
const coins = [];
for (const [id, g] of Object.entries(groups).sort(([a], [b]) => a.localeCompare(b))) {
  if (g.heads && g.tails) coins.push({ id, heads: g.heads, tails: g.tails });
  else console.warn(`  skipped coin "${id}": needs both ${id}-heads.* and ${id}-tails.*`);
}
writeFileSync(new URL('manifest.js', coinDir), `${HEADER}window.ARCADE_COINS = ${JSON.stringify(coins, null, 2)};\n`);
console.log(`coins/manifest.js: ${coins.length} coin(s)`);
coins.forEach((c) => console.log(`  ${c.id}: ${c.heads} + ${c.tails}`));
